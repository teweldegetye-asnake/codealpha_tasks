   function defaultImages(){
        document.querySelector(".imageContainer").innerHTML = "";
    for(const allImages in images){
        images[allImages].forEach(imageItems => {
            const div = document.createElement("div");
            div.classList.add("div");
            document.querySelector(".imageContainer").appendChild(div);
            div.classList.add("class");
            const image = document.createElement("img");
            image.src = imageItems.src;
            image.alt = allImages + " picture";
            div.appendChild(image);
            image.classList.add("image");
            const discription = document.createElement("p");
            discription.textContent = "Description: " + imageItems.value;
            div.appendChild(discription);
            $(discription).hide();
        });
    }
}
